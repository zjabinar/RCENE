export const aiStrings = extendStrings(common, { en, war, fil });

export type AiStrings = typeof aiStrings;

/** `aiStrings` with the app's table (AppShell `strings`) layered on top. */
export function useAiStrings(): AiStrings {
  const app = useAppStrings();
  return useMemo(
    () => ({
      en: { ...aiStrings.en, ...app.en },
      war: { ...aiStrings.war, ...app.war },
      fil: { ...aiStrings.fil, ...app.fil },
    }),
    [app],
  );
}
